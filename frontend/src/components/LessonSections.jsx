function cleanTitle(title) {
  return title.replace(/\*\*/g, "").replace(/#/g, "").trim();
}

function parseSections(markdown) {
  /**
   * Split lesson markdown into named sections.
   *
   * Handles four heading patterns generated by different LLMs / system prompts:
   *   1. Numbered+hash:  "## 1. What you will learn"   or  "1. What you will learn"
   *   2. Numbered+bold:  "**1. What You Will Learn**"
   *   3. Hash only:      "## What you will learn"       or  "# Overview"
   *   4. Bold only:      "**What you will learn**"      (standalone line)
   *
   * Patterns 3 and 4 were silently missed by the old regex (\d+\. required),
   * causing entire multi-section lessons to collapse into ONE card.
   */
  const lines = markdown.split("\n");
  const sections = [];
  let currentTitle = null;   // null = content before first heading (preamble)
  let currentContent = [];

  // Returns the captured title string if this line is a section heading, else null.
  function detectHeading(line) {
    // Pattern 1 & 2: numbered heading with optional # or ** wrapper
    //   "1. Title"  |  "## 1. Title"  |  "**1. Title**"  |  "## **1. Title**"
    // Guard: reject numbered LIST ITEMS (end with . or ?, or longer than 65 chars)
    //   "1. Read the sentence carefully..."  ← list item, NOT a heading
    //   "1. What you will learn"             ← heading ✅
    let m = line.match(/^#{0,3}\s*\**\s*(\d+\.\s+.+?)\**\s*$/);
    if (m) {
      const captured = m[1].replace(/^\d+\.\s*/, "").trim();
      // Real section headings: short, no terminal punctuation, title-like
      if (captured.length <= 65 && !/[.?!]$/.test(captured)) {
        return captured;
      }
    }

    // Pattern 3: markdown heading WITHOUT a number (## or ###)
    //   "## What you will learn"  |  "### Step-by-step breakdown"
    m = line.match(/^#{1,3}\s+(.+)$/);
    if (m) {
      const title = m[1].replace(/\*\*/g, "").trim();
      // Skip very short titles that are just decorative ("---" wrapped in ##)
      if (title.length >= 3) return title;
    }

    // Pattern 5: "Step N: Title" style headings (plain text, no markdown wrapper)
    //   "Step 2: Worked Examples"    ← IS a heading (no terminal .)
    //   "Step 1: Identify the problem."  ← NOT a heading (ends with .)
    //   "Question: Title"            ← IS a heading if short and no terminal .
    m = line.match(/^(Step\s+\d+|Question|Summary|Introduction|Conclusion|Common\s+Mistake|Quick\s+Check|What\s+You\s+Will\s+Learn|Worked\s+Example|Overview)\s*:\s*(.*)$/i);
    if (m) {
      const label = m[1].trim();
      const rest = (m[2] || "").trim();
      const combined = rest ? `${label}: ${rest}` : label;
      // Reject if combined title ends with sentence punctuation (it's a list item, not a heading)
      if (combined.length >= 3 && combined.length <= 70 && !/[.?!]$/.test(combined)) {
        return combined;
      }
    }

    // Pattern 4: standalone bold line used as a heading
    //   "**What you will learn:**"  |  "**Summary**"
    // Must be the ENTIRE line (no surrounding prose), and long enough to be a heading.
    m = line.match(/^\*\*(.+?)\*\*:?\s*$/);
    if (m) {
      const title = m[1].trim();
      // Only treat as heading if it looks like a section title:
      // - doesn't start with a lowercase pronoun (avoids matching bold mid-sentence)
      // - length 4-80 chars
      if (title.length >= 4 && title.length <= 80 && !/^[a-z]/.test(title)) {
        return title;
      }
    }

    return null;
  }

  for (const line of lines) {
    const title = detectHeading(line);
    if (title) {
      if (currentContent.join("\n").trim()) {
        sections.push({
          title: cleanTitle(currentTitle || "Introduction"),
          content: currentContent.join("\n"),
        });
      }
      currentTitle = title;
      currentContent = [];
    } else {
      currentContent.push(line);
    }
  }

  if (currentContent.join("\n").trim()) {
    sections.push({
      title: cleanTitle(currentTitle || "Introduction"),
      content: currentContent.join("\n"),
    });
  }

  return sections;
}

function cleanQuestionText(text) {
  return text
    .replace(/```[\s\S]*?```/g, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/[#*_`>]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function getQuestionPrompt(section) {
  const title = section.title.toLowerCase();
  const content = cleanQuestionText(section.content);
  const invitationOnly =
    /would you like (that|to|me to)\??$/i.test(content) ||
    /^(if you want|would you like|do you want|shall we|we can now)\b/i.test(content);
  if (invitationOnly) return "";

  const isQuestionSection =
    title.includes("question") || title.includes("quick check") ||
    title.includes("self check") || title.includes("practice");

  const labelledQuestionMatch = content.match(
    /(?:^|\s)(?:question|quick check(?: question)?|try this|your turn)\s*:\s*([^]+?)(?=(?:\s(?:step\s*\d+|answer|hint|solution)\s*:)|$)/i
  );
  if (labelledQuestionMatch) {
    const prompt = labelledQuestionMatch[1].trim();
    if (/^would you like (that|to|me to)\??$/i.test(prompt)) return "";
    return prompt;
  }
  if (isQuestionSection) return content;

  const finalQuestionMatch = content.match(/([^.!?]*\?)\s*$/);
  if (finalQuestionMatch) {
    const prompt = finalQuestionMatch[1].trim();
    if (prompt.length >= 12 && !/^would you like (that|to|me to)\??$/i.test(prompt)) return prompt;
  }
  return "";
}

function getRenderableContent(section, questionPrompt) {
  if (!questionPrompt) return section.content;

  // ── Key fix: if "Question:" is followed by a solution (Step N:, Answer:, etc.)
  // the content is a WORKED EXAMPLE — show full body INCLUDING the question+solution.
  // The question also shows in the inline box. Both coexist.
  const afterQuestion = section.content.split(/question\s*:/i)[1] || "";
  const hasSolution = /(?:step\s+\d+|answer\s*:|solution\s*:|therefore|hint\s*:)/i.test(afterQuestion);
  if (hasSolution) {
    return section.content;  // Show everything — don't discard the solution
  }

  const title = section.title.toLowerCase();
  const withoutLabelledQuestion = section.content.replace(
    /(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*)?(?:question|quick check(?: question)?|try this|your turn)(?:\*\*)?\s*:\s*[\s\S]*$/i,
    ""
  );
  if (withoutLabelledQuestion !== section.content) return withoutLabelledQuestion.trim();
  if (title.includes("question") || title.includes("quick check") || title.includes("self check") || title.includes("practice"))
    return "";
  const escapedPrompt = questionPrompt.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return section.content.replace(new RegExp(`${escapedPrompt}\\s*$`), "").trim();
}

function isHindiSubject(subject) {
  const s = (subject || "").toLowerCase();
  return s.includes("hindi") || s.includes("हिंदी") || s.includes("हिन्दी");
}

function formatMcqPrompt(prompt) {
  if (!prompt) return prompt;
  return prompt
    .replace(/\s+---+\s*$/, "")
    .replace(/\s+([a-dA-D]\))\s+/g, "\n$1 ")
    .replace(/^\s*([a-dA-D]\))\s+/g, "\n$1 ")
    .trim();
}

// ── Shared ReactMarkdown code renderer (used by both layouts) ─────────────────
function LessonMarkdownCode({ className, children, node }) {
  const language = className || "";
  const raw = String(children).replace(/\n$/, "");

  if (/language-visual-json/.test(language)) return <StructuredVisualBlock raw={raw} />;
  if (/language-mermaid/.test(language)) return null;

  const isLikelyLessonContent =
    !language &&
    node?.position?.start?.line !== undefined &&
    (raw.includes("* ") || raw.includes("- ") || raw.includes(". ") || raw.split("\n").length > 1);

  if (isLikelyLessonContent) {
    const blocks = [];
    let bulletBuffer = [];
    const flushBullets = () => {
      if (bulletBuffer.length > 0) {
        blocks.push(
          <ul key={`ul-${blocks.length}`} style={{ paddingLeft: "1.4em", margin: "0.5em 0" }}>
            {bulletBuffer.map((b, j) => <li key={j} style={{ marginBottom: "0.3em" }}>{b}</li>)}
          </ul>
        );
        bulletBuffer = [];
      }
    };
    raw.split("\n").forEach((line, i) => {
      const trimmed = line.trim();
      if (!trimmed) { flushBullets(); return; }
      if (trimmed.startsWith("* ") || trimmed.startsWith("- ")) {
        bulletBuffer.push(trimmed.slice(2));
      } else {
        flushBullets();
        blocks.push(<p key={`p-${i}`} style={{ margin: "0.4em 0" }}>{trimmed}</p>);
      }
    });
    flushBullets();
    return <div className="lesson-unwrapped-block">{blocks}</div>;
  }
  return <code className={className}>{children}</code>;
}

// ── Option A: single card in the scrollable feed ──────────────────────────────
function CardFeedSection({
  section,
  index,
  subject,
  questionModes,
  setQuestionModes,
  questionAnswers,
  setQuestionAnswers,
  questionFeedback,
  setQuestionFeedback,
  questionLoading,
  setQuestionLoading,
  onEvaluateQuestion,
}) {
  const type = getSectionType(section.title);
  const colours = CARD_TYPES[type];
  const questionPrompt = getQuestionPrompt(section);
  const renderableContent = getRenderableContent(section, questionPrompt);
  const questionMode = questionModes[index] || "";
  const answer = questionAnswers[index] || "";
  const feedback = questionFeedback[index] || "";
  const loading = questionLoading[index] || false;

  async function handleEvaluate() {
    if (!answer.trim() || !onEvaluateQuestion) return;
    setQuestionLoading((prev) => ({ ...prev, [index]: true }));
    setQuestionFeedback((prev) => ({ ...prev, [index]: "" }));
    try {
      const result = await onEvaluateQuestion({ question: questionPrompt, answer });
      setQuestionFeedback((prev) => ({
        ...prev,
        [index]: result?.evaluation || result?.message || "Your answer has been reviewed.",
      }));
    } catch {
      setQuestionFeedback((prev) => ({ ...prev, [index]: "Could not evaluate this answer right now." }));
    } finally {
      setQuestionLoading((prev) => ({ ...prev, [index]: false }));
    }
  }

  return (
    <div
      className={`lesson-card-feed-item lesson-card-type-${type}`}
      style={{
        borderRadius: 14,
        padding: "16px 18px",
        border: `1.5px solid ${colours.border}`,
        background: colours.bg,
        marginBottom: 14,
      }}
    >
      {/* Card header */}
      <div style={{ display: "flex", alignItems: "center", gap: 8, marginBottom: 12 }}>
        <span style={{
          width: 28, height: 28, borderRadius: 8,
          background: colours.iconBg,
          display: "flex", alignItems: "center", justifyContent: "center",
          fontSize: ".9rem", flexShrink: 0,
        }}>
          {colours.icon}
        </span>
        <span style={{
          fontSize: ".62rem", fontWeight: 800, textTransform: "uppercase",
          letterSpacing: ".1em", color: colours.labelColor, marginRight: 4,
        }}>
          {colours.label}
        </span>
        <span style={{ fontSize: ".92rem", fontWeight: 700, lineHeight: 1.3 }}>
          <ReactMarkdown
            remarkPlugins={[remarkGfm, remarkMath]}
            rehypePlugins={[rehypeKatex]}
            components={{ p: ({ children }) => <>{children}</> }}
          >
            {`${index + 1}. ${section.title}`}
          </ReactMarkdown>
        </span>
      </div>

      {/* Card body — rendered markdown */}
      {renderableContent && (
        <div className="lesson-section-body lesson-card-body" style={{ fontSize: ".9rem", lineHeight: 1.7 }}>
          <ReactMarkdown
            remarkPlugins={[remarkGfm, remarkMath]}
            rehypePlugins={[rehypeKatex]}
            components={{ code: LessonMarkdownCode }}
          >
            {renderableContent}
          </ReactMarkdown>
        </div>
      )}

      {/* Inline question block — same logic as before */}
      {questionPrompt && (
        <div className="lesson-inline-question-box" style={{ marginTop: 14 }}>
          <div>
            <p className="lesson-inline-question-label">Want to try this question?</p>
            <div className="lesson-inline-question-text">
              <ReactMarkdown
                remarkPlugins={[remarkGfm, remarkMath]}
                rehypePlugins={[rehypeKatex]}
              >
                {formatMcqPrompt(questionPrompt)}
              </ReactMarkdown>
            </div>
          </div>

          <div className="lesson-inline-question-actions">
            {!isHindiSubject(subject) && (
              <button
                type="button"
                className={questionMode === "answer" ? "inline-question-choice active" : "inline-question-choice"}
                onClick={() => setQuestionModes((prev) => ({ ...prev, [index]: "answer" }))}
              >
                Answer and evaluate
              </button>
            )}
            <button
              type="button"
              className={
                questionMode === "think" || isHindiSubject(subject)
                  ? "inline-question-choice active muted"
                  : "inline-question-choice muted"
              }
              onClick={() => setQuestionModes((prev) => ({ ...prev, [index]: "think" }))}
            >
              Leave for thinking
            </button>
          </div>

          {questionMode === "think" && (
            <p className="lesson-inline-thinking-note">
              Saved as a thinking prompt. No answer will be checked.
            </p>
          )}

          {questionMode === "answer" && (
            <div className="lesson-inline-answer-panel">
              <textarea
                value={answer}
                onChange={(e) => setQuestionAnswers((prev) => ({ ...prev, [index]: e.target.value }))}
                placeholder="Write your answer here..."
                rows={4}
              />
              <button
                type="button"
                className="primary-btn lesson-inline-evaluate-btn"
                disabled={!answer.trim() || loading}
                onClick={handleEvaluate}
              >
                {loading ? "Evaluating..." : "Evaluate my answer"}
              </button>
              {feedback && (
                <div className="lesson-inline-feedback">
                  <ReactMarkdown
                    remarkPlugins={[remarkGfm, remarkMath]}
                    rehypePlugins={[rehypeKatex]}
                  >
                    {feedback}
                  </ReactMarkdown>
                </div>
              )}
            </div>
          )}
        </div>
      )}
    </div>
  );
}

